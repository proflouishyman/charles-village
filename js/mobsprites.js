// Mob sprites for the Fundations Mob Battle (docs/fundations.md). Original pixel art in a Minecraft style, no Mojang
// assets. Same shape as SPRITES in sprites.js: { name: { rows: [...] } }, '.' is transparent, rows of one sprite share one
// width. Each mob faces the player; all are large (16+ wide, bosses up to 32x32) with a dark outline and high contrast so a
// 6-year-old recognises them at a glance. The word sign is a separate HTML/CSS overlay, never part of the art.
//
// Colours: every char is a key of sprites.js PALETTE or of MOB_PALETTE below. MOB_PALETTE only ADDS keys (none collides with
// PALETTE; tests/js/mobsprites.test.mjs checks that). A renderer merges them: `{ ...PALETTE, ...MOB_PALETTE }`, then
// fills one rect per non-'.' char exactly as spriteCanvas does. sprites.js is not edited and spriteElement does not know
// these names, so draw them with mobElement-style code (see mob_sheet.html / the foundation task's renderer).

